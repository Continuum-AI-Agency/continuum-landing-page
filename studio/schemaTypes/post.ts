import {defineArrayMember, defineField, defineType} from 'sanity'

const CATEGORIES = [
  'AI Strategy',
  'Creative Automation',
  'Engineering',
  'Founder Story',
  'Insights',
  'Performance Marketing',
  'Vision',
]

const today = () => new Date().toISOString().slice(0, 10)

export const post = defineType({
  name: 'post',
  title: 'Post',
  type: 'document',
  groups: [
    {name: 'article', title: 'Article', default: true},
    {name: 'seo', title: 'SEO'},
    {name: 'press', title: 'Press coverage'},
  ],
  fields: [
    defineField({
      name: 'title',
      type: 'string',
      group: 'article',
      description: 'The headline on the page (the only H1).',
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'slug',
      type: 'slug',
      group: 'article',
      description: 'The URL: /blog/<slug>/. Changing it after publishing breaks existing links.',
      options: {source: 'title', maxLength: 80},
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'excerpt',
      type: 'text',
      rows: 3,
      group: 'article',
      description: 'Shown on the blog list and in structured data.',
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'category',
      type: 'string',
      group: 'article',
      options: {list: CATEGORIES},
      initialValue: 'Insights',
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'author',
      type: 'string',
      group: 'article',
      initialValue: 'Michelle Shocron',
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'authorTitle',
      title: 'Author title',
      type: 'string',
      group: 'article',
      initialValue: 'Founder & CEO',
    }),
    defineField({
      name: 'pubDate',
      title: 'Publish date',
      type: 'date',
      group: 'article',
      initialValue: today,
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'updatedDate',
      title: 'Last updated',
      type: 'date',
      group: 'article',
      description: 'Set when you make a meaningful edit; search engines read it.',
    }),
    defineField({
      name: 'coverImage',
      title: 'Cover image',
      type: 'image',
      group: 'article',
      description: 'Used for link previews (cropped to 1200×630). Leave empty to use the site card.',
      options: {hotspot: true},
      fields: [defineField({name: 'alt', type: 'string', title: 'Alt text'})],
    }),
    defineField({name: 'content', title: 'Body', type: 'content', group: 'article'}),
    defineField({
      name: 'faq',
      title: 'FAQ',
      type: 'array',
      group: 'article',
      description: 'Shown as an FAQ and sent to Google as FAQ structured data.',
      of: [defineArrayMember({type: 'faqItem'})],
    }),

    defineField({
      name: 'metaTitle',
      title: 'Search title',
      type: 'string',
      group: 'seo',
      description: 'The title in Google, 60 characters max. Empty uses "Title | Continuum".',
      validation: (rule) => rule.max(60),
    }),
    defineField({
      name: 'metaDescription',
      title: 'Search description',
      type: 'text',
      rows: 3,
      group: 'seo',
      description: 'The snippet under the title in Google. Aim for 140–160 characters.',
      validation: (rule) => [rule.required().max(160), rule.min(120).warning('Short descriptions waste the snippet.')],
    }),
    defineField({
      name: 'targetKeyword',
      title: 'Target keyword',
      type: 'string',
      group: 'seo',
      description: 'The search phrase this post should rank for. Put it in the search title.',
    }),

    defineField({
      name: 'press',
      title: 'Press coverage',
      type: 'boolean',
      group: 'press',
      description: 'Also list this post on /press.',
      initialValue: false,
    }),
    defineField({
      name: 'sourcePublication',
      title: 'Publication',
      type: 'string',
      group: 'press',
      hidden: ({document}) => !document?.press,
    }),
    defineField({
      name: 'sourceUrl',
      title: 'Original article URL',
      type: 'url',
      group: 'press',
      hidden: ({document}) => !document?.press,
    }),
    defineField({
      name: 'sourceAuthor',
      title: 'Journalist',
      type: 'string',
      group: 'press',
      hidden: ({document}) => !document?.press,
    }),
    defineField({
      name: 'sourceDate',
      title: 'Published there on',
      type: 'date',
      group: 'press',
      hidden: ({document}) => !document?.press,
    }),
  ],
  orderings: [{title: 'Newest first', name: 'pubDateDesc', by: [{field: 'pubDate', direction: 'desc'}]}],
  preview: {
    select: {title: 'title', date: 'pubDate', category: 'category', media: 'coverImage'},
    prepare: ({title, date, category, media}) => ({title, subtitle: [date, category].filter(Boolean).join(' · '), media}),
  },
})
